@torch.no_grad()
def estimate_class_freq(loader, num_classes):
    counts = torch.zeros(num_classes, dtype=torch.long)
    for imgs, masks in loader:
        # masks: [B,H,W]
        counts += torch.bincount(masks.view(-1), minlength=num_classes)[:num_classes]
    freq = counts.float() / counts.sum().clamp_min(1)
    return counts, freq

