"""# EMA helper

"""

class EMA:
    def __init__(self, model, decay=0.999):
        self.decay = decay
        self.shadow = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}

    @torch.no_grad()
    def update(self, model):
        for k, v in model.state_dict().items():
            if v.dtype.is_floating_point:
                self.shadow[k].mul_(self.decay).add_(v.detach().cpu(), alpha=1 - self.decay)
            else:
                self.shadow[k] = v.detach().cpu().clone()

    @torch.no_grad()
    def apply_to(self, model):
        device = next(model.parameters()).device
        ema_state = {k: v.to(device) for k, v in self.shadow.items()}
        model.load_state_dict(ema_state, strict=False)

ema = EMA(model, decay=0.999)
print("EMA ready (decay=0.999).")

