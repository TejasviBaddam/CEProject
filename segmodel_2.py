import torch.nn.functional as F

def upsample_logits(logits, target):
    H, W = target.shape[-2], target.shape[-1]
    return F.interpolate(logits, size=(H, W), mode="bilinear", align_corners=False)

class CEDiceLoss(nn.Module):
    def __init__(self, class_weights=None, smooth=1.0, ignore_index=-100):
        super().__init__()
        self.ce = nn.CrossEntropyLoss(weight=class_weights, ignore_index=ignore_index)
        self.smooth = smooth
        self.ignore_index = ignore_index
        self.class_weights = class_weights

    def forward(self, logits, target):
        logits = upsample_logits(logits, target)
        ce = self.ce(logits, target)

        # Dice on valid pixels
        with torch.no_grad():
            valid = target.ne(self.ignore_index)
        if valid.sum() == 0:
            return ce

        probs = F.softmax(logits, dim=1).permute(0,2,3,1)[valid]   # (V,C)
        tgt_oh = F.one_hot(target[valid], num_classes=logits.shape[1]).float()  # (V,C)

        inter = (probs * tgt_oh).sum(dim=0)                             # (C,)
        union = probs.sum(dim=0) + tgt_oh.sum(dim=0)                    # (C,)
        dice = (2*inter + self.smooth) / (union + self.smooth)          # (C,)

        if self.class_weights is not None:
            w = (self.class_weights / self.class_weights.sum()).detach()
            dice_loss = 1.0 - (dice * w).sum()
        else:
            dice_loss = 1.0 - dice.mean()

        return ce + 0.5 * dice_loss

criterion = CEDiceLoss(class_weights=class_weights, ignore_index=IGNORE_INDEX)

