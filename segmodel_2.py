from typing import List, Tuple

def pair_files(img_dir: str, mask_dir: str) -> List[Tuple[str, str]]:
    imgs = sorted([f for f in os.listdir(img_dir) if f.endswith(".jpg")])
    pairs, missing = [], 0
    for fn in imgs:
        mname = fn.replace("image", "label").replace(".jpg", ".png")
        ip = os.path.join(img_dir, fn)
        mp = os.path.join(mask_dir, mname)
        if os.path.isfile(mp): pairs.append((ip, mp))
        else: missing += 1
    if missing: print(f"{missing} masks missing for images in {img_dir}")
    return pairs

