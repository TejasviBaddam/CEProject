def pixel_accuracy(pred, target, ignore_index=-100):
    mask = target.ne(ignore_index)
    correct = (pred.eq(target) & mask).sum().item()
    total   = mask.sum().item()
    return correct / max(total, 1)

@torch.no_grad()
def confusion_matrix(pred, target, num_classes, ignore_index=-100):
    mask = target.ne(ignore_index)
    pred = pred[mask]
    tgt  = target[mask]
    cm = torch.bincount(
        (tgt * num_classes + pred).view(-1),
        minlength=num_classes * num_classes
    ).reshape(num_classes, num_classes)
    return cm

def miou_from_confmat(cm):
    tp = cm.diag().float()
    fp = cm.sum(0).float() - tp
    fn = cm.sum(1).float() - tp
    denom = tp + fp + fn
    iou = torch.where(denom > 0, tp / denom.clamp_min(1), torch.zeros_like(tp))
    return float(iou.mean().item()), iou

