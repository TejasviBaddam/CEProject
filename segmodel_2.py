def resize_and_pad(img_pil: Image.Image, mask_pil: Image.Image, target_hw=(512, 384)):
    th, tw = target_hw
    w, h = img_pil.size
    scale = min(th / h, tw / w)
    nh, nw = int(round(h * scale)), int(round(w * scale))

    img_rs  = img_pil.resize((nw, nh), Image.BILINEAR)
    mask_rs = mask_pil.resize((nw, nh), Image.NEAREST)

    pad_h, pad_w = th - nh, tw - nw
    top, left = pad_h // 2, pad_w // 2

    new_img  = Image.new("RGB", (tw, th), (0, 0, 0))
    new_mask = Image.new("L",   (tw, th), 0)
    new_img.paste(img_rs,  (left, top))
    new_mask.paste(mask_rs,(left, top))
    return new_img, new_mask

def train_transform(img_pil: Image.Image, mask_pil: Image.Image):
    if random.random() < 0.5:
        img_pil  = TF.hflip(img_pil)
        mask_pil = TF.hflip(mask_pil)
    angle = random.uniform(-10, 10)
    img_pil  = TF.rotate(img_pil, angle, interpolation=InterpolationMode.BILINEAR, fill=0)
    mask_pil = TF.rotate(mask_pil, angle, interpolation=InterpolationMode.NEAREST,  fill=0)

    if random.random() < 0.7:
        s = random.uniform(0.85, 1.35)
        nw, nh = int(img_pil.width * s), int(img_pil.height * s)
        img_pil  = img_pil.resize((nw, nh), Image.BILINEAR)
        mask_pil = mask_pil.resize((nw, nh), Image.NEAREST)
    img_pil, mask_pil = resize_and_pad(img_pil, mask_pil, IMAGE_SIZE)
    if random.random() < 0.5:
        jitter = ColorJitter(brightness=0.2, contrast=0.2, saturation=0.1, hue=0.02)
        img_pil = jitter(img_pil)
    img  = TF.to_tensor(img_pil)
    img  = TF.normalize(img, mean=[0.485, 0.456, 0.406],
                             std=[0.229, 0.224, 0.225])
    mask = torch.as_tensor(np.array(mask_pil, dtype=np.int64))
    return img, mask

def val_transform(img_pil: Image.Image, mask_pil: Image.Image):
    img_pil, mask_pil = resize_and_pad(img_pil, mask_pil, IMAGE_SIZE)
    img  = TF.to_tensor(img_pil)
    img  = TF.normalize(img, mean=[0.485, 0.456, 0.406],
                             std=[0.229, 0.224, 0.225])
    mask = torch.as_tensor(np.array(mask_pil, dtype=np.int64))
    return img, mask

